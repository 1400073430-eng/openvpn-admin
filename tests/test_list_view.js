const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
const path = require('path');
const sandbox = {document: {}, sessionStorage: {}, setTimeout() {}};
sandbox.window = sandbox;
vm.runInNewContext(fs.readFileSync(path.join(__dirname, '../frontend/js/api.js'), 'utf8'), sandbox);
const view = sandbox.window.ListView;
const tbody = {innerHTML: ''};
assert.strictEqual(view.url('/api/clients', 2, 10, 'a&b'), '/api/clients?page=2&page_size=10&keyword=a%26b');
view.loading(tbody, 5);
assert(tbody.innerHTML.includes('加载中'));
view.empty(tbody, 6, '📋', '<img src=x>');
assert(tbody.innerHTML.includes('&lt;img src=x&gt;'));
assert(!tbody.innerHTML.includes('<img'));
view.error(tbody, 5, {message: '<script>alert(1)</script>'});
assert(tbody.innerHTML.includes('&lt;script&gt;'));
assert(!tbody.innerHTML.includes('<script>'));
console.log('PASS: shared list states and escaping');
